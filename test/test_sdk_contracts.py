@pytest.mark.parametrize('model_cls', STRUCT_MODELS, ids=lambda c: c.__name__)
class TestGeneratedModels:

    def test_round_trip_with_all_fields(self, model_cls):
        data = build_model(model_cls).to_dict()

        assert_round_trip(model_cls, data)
        from_json = model_cls.from_json(json.dumps(to_wire(data))).to_dict()
        assert_preserved(model_cls, data, from_json)

    def test_to_json_matches_to_dict(self, model_cls):
        data = build_model(model_cls).to_dict()
        wire = to_wire(data)
        if wire != data:
            pytest.skip('contains non-JSON-native values (e.g. datetime)')
        instance = model_cls.from_dict(data)
        assert json.loads(instance.to_json()) == instance.to_dict()

    def test_required_fields_only(self, model_cls):
        data = build_model(model_cls, include_optional=False).to_dict()
        assert_round_trip(model_cls, data)

    def test_explicit_nulls_round_trip(self, model_cls):
        nullable = [
            name for name, field in model_cls.model_fields.items()
            if not field.is_required() and _is_nullable(field.annotation)
        ]
        if not nullable:
            pytest.skip('no nullable fields')
        base = build_model(model_cls, include_optional=False)
        values = {name: getattr(base, name) for name in base.model_fields_set}
        instance = model_cls(**{**values, **{name: None for name in nullable}})
        assert_round_trip(model_cls, instance.to_dict())

    def test_missing_required_field_is_rejected(self, model_cls):
        required = required_aliases(model_cls)
        if not required:
            pytest.skip('no required fields')
        data = build_model(model_cls, include_optional=False).to_dict()
        data.pop(required[0], None)
        with pytest.raises(ValidationError):
            model_cls.from_dict(data)

    def test_invalid_enum_value_is_rejected(self, model_cls):
        rules = _validator_rules(model_cls)
        enum_fields = [name for name, rule in rules.items() if rule[0] == 'enum']
        if not enum_fields:
            pytest.skip('no enum-validated fields')
        instance = build_model(model_cls)
        for name in enum_fields:
            with pytest.raises(ValidationError):
                setattr(instance, name, 'definitely-not-a-valid-value')

    def test_string_and_helpers(self, model_cls):
        instance = build_model(model_cls)
        assert model_cls.from_dict(None) is None
        assert model_cls.from_dict(instance) == instance
        assert isinstance(instance.to_str(), str)


