def _string_matching(pattern):
    """Return a short string that matches ``pattern`` (supports the subset of
    regex syntax used by OpenAPI schemas)."""

    def build(parsed):
        out = []
        for op, arg in parsed:
            name = getattr(op, "name", str(op))
            if name == 'LITERAL':
                out.append(chr(arg))
            elif name == 'ANY':
                out.append('a')
            elif name == 'IN':
                out.append(pick(arg))
            elif name in ('MAX_REPEAT', 'MIN_REPEAT', 'POSSESSIVE_REPEAT'):
                low, high, sub = arg
                count = max(low, 1)
                if high is not sre_parse.MAXREPEAT:
                    count = min(count, high)
                out.append(build(sub) * count)
            elif name == 'SUBPATTERN':
                out.append(build(arg[-1]))
            elif name == 'BRANCH':
                out.append(build(arg[1][0]))
            elif name == 'CATEGORY':
                out.append(category(arg))
        return ''.join(out)

    def category(cat):
        cat = getattr(cat, "name", str(cat))
        if 'DIGIT' in cat and 'NOT' not in cat:
            return '1'
        if 'SPACE' in cat and 'NOT' not in cat:
            return ' '
        return 'a'

    def pick(items):
        negate = any(getattr(op, "name", str(op)) == "NEGATE" for op, _ in items)
        candidates = []
        for op, arg in items:
            name = getattr(op, "name", str(op))
            if name == 'LITERAL':
                candidates.append(chr(arg))
            elif name == 'RANGE':
                candidates.append(chr(arg[0]))
            elif name == 'CATEGORY':
                candidates.append(category(arg))
        if negate:
            return next(c for c in 'aZ1_-' if c not in candidates)
        # Prefer letters so identifiers stay readable.
        letters = [c for c in candidates if c.isalpha()]
        return (letters or candidates or ['a'])[0]

    value = build(sre_parse.parse(pattern))
    assert re.match(pattern, value), f'could not build a sample for /{pattern}/'
    return value


def _validator_rules(model_cls):
    """Map field name -> ('enum', values) or ('pattern', regex) from the
    generated @field_validator functions."""
    rules = {}
    decorators = model_cls.__pydantic_decorators__.field_validators.values()
    for decorator in decorators:
        source = _source(decorator.func)
        enum_match = re.search(r'set\((\[.*?\])\)', source)
        pattern_match = re.search(r're\.match\(r"(.*?)", ', source)
        for field_name in decorator.info.fields:
            if enum_match:
                rules[field_name] = ('enum', ast.literal_eval(enum_match.group(1)))
            elif pattern_match:
                rules[field_name] = ('pattern', pattern_match.group(1))
    return rules


def _base_type(annotation):
    while typing_extensions.get_origin(annotation) is typing_extensions.Annotated:
        annotation = typing_extensions.get_args(annotation)[0]
    return annotation


def _unwrap(annotation, constraints):
    """Strip Optional/Annotated wrappers, collecting constraint metadata."""
    while True:
        origin = typing_extensions.get_origin(annotation)
        if origin is typing_extensions.Annotated:
            annotation, *metadata = typing_extensions.get_args(annotation)
            for item in metadata:
                if isinstance(item, FieldInfo):
                    constraints.extend(item.metadata)
                else:
                    constraints.append(item)
        elif origin is typing.Union:
            args = [a for a in typing_extensions.get_args(annotation) if a is not type(None)]
            # A `format: byte` field is Union[StrictBytes, StrictStr]: on the
            # wire it is base64 text, so sample its str member.
            bases = [_base_type(a) for a in args]
            if str in bases and any(b in (bytes, bytearray) for b in bases):
                annotation = args[bases.index(str)]
            else:
                annotation = args[0]
        else:
            return annotation


def _constraint(constraints, kind, attr):
    for item in constraints:
        if isinstance(item, kind) and getattr(item, attr, None) is not None:
            return getattr(item, attr)
    return None


def _sample_number(constraints, base):
    ge = _constraint(constraints, annotated_types.Ge, 'ge')
    gt = _constraint(constraints, annotated_types.Gt, 'gt')
    le = _constraint(constraints, annotated_types.Le, 'le')
    lt = _constraint(constraints, annotated_types.Lt, 'lt')
    multiple = _constraint(constraints, annotated_types.MultipleOf, 'multiple_of')
    value = base(1)
    if ge is not None:
        value = max(value, base(ge))
    if gt is not None:
        value = max(value, base(gt) + 1)
    if multiple:
        value = base(multiple) * max(1, -(-value // base(multiple)))
    if le is not None:
        value = min(value, base(le))
    if lt is not None:
        value = min(value, base(lt) - 1)
    return value


def sample_value(annotation, depth=0, rule=None):
    constraints = []
    annotation = _unwrap(annotation, constraints)
    origin = typing_extensions.get_origin(annotation)

    if rule and rule[0] == 'enum':
        values = rule[1]
        return [values[0]] if origin in (list, set) else values[0]
    if origin in (list, set, tuple):
        args = typing_extensions.get_args(annotation)
        item = sample_value(args[0], depth + 1, rule) if args else 'item'
        count = _constraint(constraints, annotated_types.MinLen, 'min_length') or 1
        return [item] * count
    if origin is dict:
        args = typing_extensions.get_args(annotation)
        value_type = args[1] if len(args) == 2 else typing.Any
        return {'key': sample_value(value_type, depth + 1)}
    if inspect.isclass(annotation):
        if issubclass(annotation, enum.Enum):
            return next(iter(annotation))
        if issubclass(annotation, BaseModel):
            return build_model(annotation, depth + 1)
        if issubclass(annotation, bool):
            return True
        if issubclass(annotation, int):
            return _sample_number(constraints, int)
        if issubclass(annotation, (float, Decimal)):
            return float(_sample_number(constraints, float)) + 0.5
        if issubclass(annotation, datetime):
            return SAMPLE_DATETIME
        if issubclass(annotation, date):
            return SAMPLE_DATETIME.date()
        if issubclass(annotation, UUID):
            return SAMPLE_UUID
        if issubclass(annotation, (bytes, bytearray)):
            return b'sample'
        if issubclass(annotation, str):
            pattern = rule[1] if rule and rule[0] == 'pattern' else None
            pattern = pattern or _constraint(constraints, object, 'pattern')
            if pattern:
                return _string_matching(pattern)
            max_length = _constraint(constraints, annotated_types.MaxLen, 'max_length')
            min_length = _constraint(constraints, annotated_types.MinLen, 'min_length') or 0
            value = 'sample'.ljust(min_length, 'x')
            return value[:max_length] if max_length else value
    return 'sample'


def build_model(model_cls, depth=0, include_optional=True):
    """Instantiate ``model_cls`` with valid values for every field."""
    if 'actual_instance' in model_cls.model_fields:
        return None
    rules = _validator_rules(model_cls)
    values = {}
    for name, field in model_cls.model_fields.items():
        if not field.is_required() and (not include_optional or depth >= MAX_DEPTH):
            continue
        values[name] = sample_value(field.annotation, depth, rules.get(name))
    return model_cls(**values)


def to_wire(value):
    """Serialize like the SDK does when sending a request body."""
    return ApiClient().sanitize_for_serialization(value)


def _is_nullable(annotation):
    while typing_extensions.get_origin(annotation) is typing_extensions.Annotated:
        annotation = typing_extensions.get_args(annotation)[0]
    return typing_extensions.get_origin(annotation) is typing.Union and type(None) in typing_extensions.get_args(annotation)


def _nested_model(annotation):
    inner = _unwrap(annotation, [])
    if typing_extensions.get_origin(inner) in (list, set, tuple):
        inner = _unwrap(typing_extensions.get_args(inner)[0], [])
    return inner if inspect.isclass(inner) and issubclass(inner, BaseModel) else None


def assert_preserved(model_cls, expected, actual):
    """Every value in ``expected`` survives in ``actual``. ``from_dict`` may
    add keys that were absent: explicit nulls for nullable fields and schema
    defaults, which is how the generated models are designed to behave."""
    fields = {(f.alias or n): f for n, f in model_cls.model_fields.items()}
    for key, value in expected.items():
        assert key in actual, f'{model_cls.__name__}.{key} was dropped'
        nested = _nested_model(fields[key].annotation) if key in fields else None
        if nested and isinstance(value, dict):
            assert_preserved(nested, value, actual[key])
        elif nested and isinstance(value, list):
            assert len(actual[key]) == len(value)
            for e, a in zip(value, actual[key]):
                assert_preserved(nested, e, a)
        else:
            assert actual[key] == value, f'{model_cls.__name__}.{key} changed'
    for key in set(actual) - set(expected):
        field = fields.get(key)
        assert field is not None, f'{model_cls.__name__} gained unknown key {key}'
        assert actual[key] is None or actual[key] == field.default, (
            f'{model_cls.__name__}.{key} appeared with a non-default value')


def assert_round_trip(model_cls, data):
    restored = model_cls.from_dict(data).to_dict()
    assert_preserved(model_cls, data, restored)
    assert model_cls.from_dict(restored).to_dict() == restored


def required_aliases(model_cls):
    return [
        field.alias or name
        for name, field in model_cls.model_fields.items()
        if field.is_required()
    ]


