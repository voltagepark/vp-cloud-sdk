@pytest.mark.parametrize(
    'api_cls,name', OPERATIONS, ids=[f'{c.__name__}.{n}' for c, n in OPERATIONS]
)
class TestGeneratedOperations:

    def test_request_is_serialized_per_spec(self, api_client, api_cls, name):
        spec = _operation_spec(api_cls, name)
        api = api_cls(api_client=api_client)
        args = _call_args(api_cls, name)
        response, _ = _success_response(spec)

        with pytest.MonkeyPatch.context() as mp:
            calls = []
            mp.setattr(api_client.rest_client, 'request',
                       lambda *a, **kw: calls.append((a, kw)) or response)
            getattr(api, name)(**args)

        (method, url), kwargs = calls[0]
        assert method == spec['method']

        expected_path = spec['path']
        for alias, arg in spec['path_params'].items():
            expected_path = expected_path.replace(
                '{' + alias + '}', quote(str(args[arg]), safe=''))
        parts = urlsplit(url)
        # Observatory operations go to observatory_host, Harbor ones to host.
        host = api_client.configuration.observatory_host if spec['service'] == 'observatory' else HOST
        assert f'{parts.scheme}://{parts.netloc}{parts.path}' == host + expected_path

        query = parse_qs(parts.query)
        for alias, arg in spec['query_params'].items():
            assert query[alias] == [str(to_wire(args[arg]))]

        for arg, header in spec['header_params'].items():
            assert kwargs['headers'][header] == str(args[arg])

        if spec['body_param']:
            assert kwargs['body'] == to_wire(args[spec['body_param']])

    def test_response_is_deserialized_per_spec(self, api_client, api_cls, name):
        spec = _operation_spec(api_cls, name)
        api = api_cls(api_client=api_client)
        args = _call_args(api_cls, name)
        response, expected = _success_response(spec)

        with pytest.MonkeyPatch.context() as mp:
            mp.setattr(api_client.rest_client, 'request', lambda *a, **kw: response)
            result = getattr(api, name)(**args)
            info = getattr(api, f'{name}_with_http_info')(**args)
            raw = getattr(api, f'{name}_without_preload_content')(**args)

        if expected is None:
            assert result is None
        else:
            _assert_matches(result, expected)
        assert info.status_code == spec['status']
        _assert_matches(info.data, expected) if expected is not None else None
        assert raw.status == spec['status']

    def test_error_status_raises(self, api_client, api_cls, name):
        api = api_cls(api_client=api_client)
        args = _call_args(api_cls, name)
        error = {'error': 'not found', 'code': 'NOT_FOUND', 'timestamp': 1700000000000}

        with pytest.MonkeyPatch.context() as mp:
            mp.setattr(api_client.rest_client, 'request',
                       lambda *a, **kw: _json_response(404, error))
            with pytest.raises(ApiException) as exc_info:
                getattr(api, name)(**args)

        assert exc_info.value.status == 404
