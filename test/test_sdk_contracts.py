def _operation_spec(api_cls, name):
    """Read the HTTP method, path, parameter wiring and success response type
    from the generated operation and its serializer."""
    serializer = _source(getattr(api_cls, f'_{name}_serialize'))
    operation = _source(getattr(api_cls, name))
    responses = dict(re.findall(r"'(\d{3})': (None|\"[^\"]+\")", operation))
    status, response_type = next((s, t) for s, t in responses.items() if s.startswith('2'))
    return {
        'method': re.search(r"method='(\w+)'", serializer).group(1),
        'path': re.search(r"resource_path='([^']+)'", serializer).group(1),
        'path_params': dict(re.findall(r"_path_params\['([^']+)'\] = (\w+)", serializer)),
        'query_params': dict(re.findall(r"_query_params\.append\(\('([^']+)', (\w+)\)\)", serializer)),
        'header_params': {
            arg: header
            for header, arg in re.findall(r"_header_params\['([^']+)'\] = (\w+)\n", serializer)
            if not arg.startswith('_')
        },
        'body_param': next(iter(re.findall(r'_body_params = (\w+)', serializer)), None),
        'service': next(iter(re.findall(r"_service='(\w+)'", serializer)), None),
        'status': int(status),
        'response_type': None if response_type == 'None' else response_type.strip('"'),
    }


def _resolve_type(type_name):
    if type_name.startswith('List['):
        return typing.List[_resolve_type(type_name[5:-1])]
    if type_name.startswith('Dict['):
        return typing.Dict[str, _resolve_type(type_name.split(',', 1)[1].strip()[:-1])]
    builtins = {'str': str, 'int': int, 'float': float, 'bool': bool, 'object': typing.Any}
    return builtins.get(type_name) or getattr(vpcloud_client.models, type_name)


def _call_args(api_cls, name):
    signature = inspect.signature(inspect.unwrap(getattr(api_cls, name)))
    return {
        param_name: sample_value(param.annotation)
        for param_name, param in signature.parameters.items()
        if param_name != 'self' and not param_name.startswith('_')
    }


def _json_response(status, payload):
    return MockResponse(
        status,
        headers={'content-type': 'application/json'},
        data=json.dumps(payload).encode(),
    )


class _RawResponse(MockResponse):
    @property
    def response(self):
        return self


def _success_response(spec):
    if spec['response_type'] is None:
        return _RawResponse(spec['status']), None
    expected = sample_value(_resolve_type(spec['response_type']))
    response = _RawResponse(
        spec['status'],
        headers={'content-type': 'application/json'},
        data=json.dumps(to_wire(expected)).encode(),
    )
    return response, expected


def _assert_matches(actual, expected):
    if isinstance(expected, BaseModel):
        assert type(actual) is type(expected)
        assert actual.to_dict() == expected.to_dict()
    elif isinstance(expected, list):
        assert len(actual) == len(expected)
        for a, e in zip(actual, expected):
            _assert_matches(a, e)
    else:
        assert to_wire(actual) == to_wire(expected)


