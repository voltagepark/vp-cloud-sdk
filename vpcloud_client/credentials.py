    def get_token(self, force_refresh: bool = False) -> str:
        """Get a valid access token, refreshing if necessary.
        
        :param force_refresh: Force token refresh even if cached token is valid
        :return: Access token (JWT)
        :raises AuthenticationError: If token exchange fails
        """
        # Check if cached token is still valid. A token is replaced refresh_margin
        # seconds before it expires, or halfway through its lifetime if that is
        # shorter, so a short-lived token is still reused rather than fetched
        # on every call.
        margin = min(self.refresh_margin, self._token_lifetime / 2) if self._token_lifetime else self.refresh_margin
        if not force_refresh and self._cached_token and time.time() < self._token_expires_at - margin:
            return self._cached_token
        
        # Exchange credentials for token
        if httpx is None:
            raise AuthenticationError(
                "httpx is required for Auth0 token exchange. "
                "Install it with: pip install httpx"
            )
        
        try:
            response = httpx.post(
                self.TOKEN_URL,
                json={
                    "client_id": self.client_id,
                    "client_secret": self.client_secret,
                    "audience": self.audience,
                    "grant_type": "client_credentials"
                },
                headers={"Content-Type": "application/json"},
                timeout=10.0
            )
            response.raise_for_status()
            data = response.json()
            
            access_token = data.get("access_token")
            if not access_token:
                raise AuthenticationError("Auth0 response missing access_token")
            
            # Cache token with expiry
            expires_in = data.get("expires_in", 86400)  # Default 24 hours
            self._cached_token = access_token
            self._token_lifetime = float(expires_in)
            self._token_expires_at = time.time() + expires_in
            
            return access_token
            
        except httpx.HTTPStatusError as e:
            status = e.response.status_code
            error, description = _auth0_error(e.response)
            detail = ": ".join(part for part in (error, description) if part)
            raise AuthenticationError(
                f"Auth0 refused the token exchange for {self.audience} with status {status}"
                + (f" ({detail})" if detail else ""),
                status_code=status,
                error=error,
                audience=self.audience,
            ) from e
        except httpx.RequestError as e:
            raise AuthenticationError(f"Auth0 token exchange request failed: {e}") from e
        except Exception as e:
            raise AuthenticationError(f"Unexpected error during Auth0 token exchange: {e}") from e

